"""Generate SONG_FORMAT.md and PRESETS.md from the schema and preset library (single source of truth).

    python -m chipforge.docgen          # write the files
    python -m chipforge.docgen --check  # exit 1 if they are stale (used by the test suite)
"""
from __future__ import annotations

import sys
from pathlib import Path

from . import chips, presets
from .mml import __doc__ as MML_DOC
from .schema import (ARR_SPEC, CHANNEL_SPEC, EVENT_SPEC, GEN_SPEC, MIX_SPEC, PATTERN_SPEC, SONG_SPEC, F)
from .theory import CHORD_QUALITIES, SCALES

ROOT = Path(__file__).resolve().parent.parent
HEADER = "<!-- GENERATED by `python -m chipforge.docgen` from chipforge/schema.py and presets.yml. Do not edit by hand. -->\n"


def _type(f: F) -> str:
    t = f.type if isinstance(f.type, tuple) else (f.type,)
    return " \\| ".join(t)


def _table(spec: dict[str, F]) -> str:
    rows = ["| field | type | default | description |", "|---|---|---|---|"]
    for k, f in spec.items():
        d = "**required**" if f.required else ("" if f.default is None else f"`{f.default}`")
        extra = ""
        if f.choices:
            extra += " One of: " + ", ".join(f"`{c}`" for c in f.choices) + "."
        if f.min is not None or f.max is not None:
            extra += f" Range {f.min if f.min is not None else ''}..{f.max if f.max is not None else ''}."
        if f.example:
            extra += f" Example: `{f.example}`."
        rows.append(f"| `{k}` | {_type(f)} | {d} | {(f.doc + extra).replace('|', chr(92) + '|')} |")
    return "\n".join(rows)


def song_format() -> str:
    out = [HEADER, "# ChipForge song format reference\n",
           "The song file is YAML. `QUICKREF.md` is the short version; this page lists every field.\n",
           "## Top level\n", _table(SONG_SPEC), "",
           "### `mix` (optional master overrides)\n", _table(MIX_SPEC), "",
           "## Channels (`channels: {name: {...}}`)\n",
           "Channel names are lowercase identifiers and are referenced by patterns.\n", _table(CHANNEL_SPEC), "",
           "## Patterns (`patterns: {name: {...}}`)\n",
           "Besides these fields, a pattern has one entry per channel it uses: an MML string or a generator "
           "mapping for melodic channels, drum lanes / an events list for kit channels.\n", _table(PATTERN_SPEC), "",
           "### Chord symbols\n",
           "`chords:` lists one bar per `|`; several symbols inside a bar split it evenly. Root `A`-`G` with `#`/`b`, "
           "then a quality, optionally `/bass`. Qualities: " + ", ".join(f"`{q}`" for q in sorted(k for k in CHORD_QUALITIES if k)) + ".\n",
           "### Scales (for `key:` and `harmony.scale`)\n", ", ".join(f"`{s}`" for s in SCALES), "",
           "## MML\n", "```text" + MML_DOC.split("MML dialect (see QUICKREF.md):")[1].rstrip() + "\n```", "",
           "Lengths are note values (4 = quarter, 8 = eighth). A string that divides the pattern length evenly "
           "repeats; a longer string is an error.\n",
           "## Drum lanes\n",
           "`{k: 'x...x...', s: '....x...'}` - one string per kit piece, one character per grid step "
           "(`step:` field, default 16ths). `.` rest, `x` 1.0, `o` 0.55, `g` 0.3, digits `1`-`9` = velocity "
           "tenths, `|` ignored. Lanes repeat if they divide the pattern evenly.\n",
           "### Events (`events: [...]` inside a kit lane mapping, or a bare list)\n", _table(EVENT_SPEC), ""]
    out += ["## Generators (`{gen: name, ...}` on a melodic channel)\n"]
    for g, spec in GEN_SPEC.items():
        out += [f"### `{g}`\n", _table(spec), ""]
    out += ["## Arrangement items\n", "A pattern name, or a mapping:\n", _table(ARR_SPEC), "",
            "## Loop semantics\n",
            "- `loop: true` (default): the whole arrangement loops; tails and reverb wrap around circularly.\n"
            "- `loop: {from: LABEL}`: sections before LABEL play once as an intro; the loop region starts at LABEL.\n"
            "  Intro tails bleed into the loop start (that is how game engines will hear it too).\n"
            "- `loop: false`: one-shot; the render keeps the natural tail and trims silence.\n"
            "Loop points are written to the WAV `smpl` chunk, OGG `LOOPSTART`/`LOOPLENGTH` and the JSON sidecar.\n",
            "## Chip profiles\n", "| chip | description |", "|---|---|"]
    out += [f"| `{n}` | {p.doc} |" for n, p in chips.PROFILES.items()]
    out += ["", OUTPUTS_DOC]
    return "\n".join(out) + "\n"


OUTPUTS_DOC = """## Outputs and loop metadata

`chipforge render song.yml -o out/ [-f wav|ogg|mp3 ...] [--bits 24] [--stems-by layer|group|channel]` writes:

| file | contents |
|---|---|
| `<title>.wav` / `.ogg` / `.mp3` | the mastered track. WAV carries a `smpl` chunk with the loop; OGG carries `LOOPSTART` / `LOOPLENGTH` Vorbis comments (samples) |
| `<title>_preview.<fmt>` | intro + loop played twice, so the seam can be auditioned |
| `<title>_intro.<fmt>`, `<title>_loop.<fmt>` | only when the song has an intro: the two pieces for engines that chain an intro into a loop |
| `<title>_stems/<stem>.<fmt>` | stems with the same loop metadata; `layerN` (adaptive intensity, default), or instrument groups `lead arp bass pads drums fx`, or one per channel. Stems sum exactly to the mix: the nonlinear stages are shared as gain curves |
| `<title>_stems/music.<fmt>`, `ambience.<fmt>` | music without the bed, and the bed alone, when `ambience:` is set |
| `<title>.mid` | one track per channel (kits on MIDI channel 10), markers for every section plus `loopStart` / `loopEnd` |
| `<title>.json` | tempo, bars, beat and bar seconds, loop start/end in samples and seconds, sections with `exits` (seconds), intensity layers with their channels and stem files, loudness (target, measured, true peak, limiter work), file paths |

Loop points are exact sample positions on the bar grid; the loop region always ends at the last sample of the file.

### Using the loop in game engines

- **Godot**: WAV loop points are read from the file ("by default, Godot will follow this metadata" - [importing audio samples](https://docs.godotengine.org/en/stable/tutorials/assets_pipeline/importing_audio_samples.html)). For OGG/MP3 enable *Loop* in the import dock and set *Loop Offset* to `loop.start_seconds` from the JSON (the loop end is the end of the file, which is how ChipForge renders).
- **RPG Maker MV/MZ**: OGG `LOOPSTART` / `LOOPLENGTH` are read natively.
- **Unity**: AudioClip has no loop points. Either use `_intro` + `_loop` with two AudioSources and `PlayScheduled`, or a looping-audio plugin that reads the WAV `smpl` chunk.
- **FMOD / Wwise**: set the loop region to `loop.start_samples` .. `loop.end_samples` in the tool, or import `_loop` with a plain loop.
- **Web Audio / Phaser**: `AudioBufferSourceNode.loop = true; loopStart = loop.start_seconds; loopEnd = loop.end_seconds`.
- **GameMaker**: `audio_sound_loop_start()` / `audio_sound_loop_end()` in seconds.
- **Adaptive music**: play the `layerN` stems in sync and fade them by intensity; switch sections horizontally at the `exits` listed per section (seconds from the start of the file).
"""


def presets_doc() -> str:
    out = [HEADER, "# ChipForge presets\n",
           "Presets live in `chipforge/presets.yml`. Melodic presets have a `voice` (or a `stack` of voices); "
           "kit presets have `pieces` keyed by a lane letter or a hit name. Mix values are the tuned reference "
           "levels; a channel's `vol` multiplies them.\n"]
    for cat, names in presets.categories().items():
        out.append(f"## {cat}\n")
        out += ["| preset | voice(s) | mix | description |", "|---|---|---|---|"]
        for n in names:
            p = presets.get(n)
            if p["kind"] == "kit":
                voices = ", ".join(f"`{k}`={v['voice']}" for k, v in p["pieces"].items())
            elif p.get("voice") == "stack":
                voices = "stack: " + " + ".join(l["voice"] for l in p["layers"])
            else:
                voices = p["voice"]
            mix = ", ".join(f"{k} {v}" for k, v in p.get("mix", {}).items())
            out.append(f"| `{n}` | {voices} | {mix} | {p.get('doc', '')} |")
        out.append("")
    out.append("## Voice parameters\n")
    for v, spec in presets.VOICES.items():
        out += [f"### `{v}`\n", "| param | default | description |", "|---|---|---|"]
        out += [f"| `{k}` | `{d}` | {doc} |" for k, (d, doc) in spec.items()]
        out.append("")
    out.append("Mix keys usable on any preset, layer or piece: " + ", ".join(f"`{k}`" for k in presets.MIX_DEFAULTS) + ".\n")
    return "\n".join(out) + "\n"


OUTPUTS = {"SONG_FORMAT.md": song_format, "PRESETS.md": presets_doc}


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    stale = []
    for name, fn in OUTPUTS.items():
        text = fn()
        path = ROOT / name
        if "--check" in argv:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8")
            print("wrote", path)
    if stale:
        print("stale generated docs:", ", ".join(stale), "- run `python -m chipforge.docgen`")
        sys.exit(1)


if __name__ == "__main__":
    main()
